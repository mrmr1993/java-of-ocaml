(* Scan [jvm_generate.ml] for the quoted primitive names that
   [emit_ccall] handles, and emit an OCaml module exposing the
   resulting list. Run at build time (dune rule) so the list never
   drifts from the source — adding a new case arm to [emit_ccall]
   automatically shows up in [Known_prims.names]. *)

let read_all path =
  let ic = open_in_bin path in
  let n = in_channel_length ic in
  let s = Bytes.create n in
  really_input ic s 0 n;
  close_in ic;
  Bytes.unsafe_to_string s

let is_name_char c =
  match c with
  | 'A' .. 'Z' | 'a' .. 'z' | '0' .. '9' | '_' -> true
  | _ -> false

(* A "primitive name" is a quoted string whose content starts with
   [caml_] or [Base_] and consists entirely of identifier chars. *)
let known_prefixes = [ "caml_"; "Base_" ]

let starts_with s prefix =
  String.length s >= String.length prefix
  && String.sub s 0 (String.length prefix) = prefix

let looks_like_prim_name s =
  List.exists (starts_with s) known_prefixes
  && String.for_all is_name_char s

(* Walk the source scanning string literals; collect those that look
   like primitive names. Conservative: skips escape sequences inside
   the quote, so "\\\"" doesn't terminate the literal. *)
module S = Set.Make (String)

let scan_names src =
  let set = ref S.empty in
  let n = String.length src in
  let i = ref 0 in
  while !i < n do
    if src.[!i] = '"'
    then (
      incr i;
      let start = !i in
      while !i < n && src.[!i] <> '"' do
        if src.[!i] = '\\' && !i + 1 < n then incr i;
        incr i
      done;
      let s = String.sub src start (!i - start) in
      if looks_like_prim_name s then set := S.add s !set;
      if !i < n then incr i)
    else incr i
  done;
  !set

let () =
  let set =
    Array.fold_left
      (fun acc path -> S.union acc (scan_names (read_all path)))
      S.empty
      (Array.sub Sys.argv 1 (Array.length Sys.argv - 1))
  in
  print_endline "(* Auto-generated by gen_known_prims.exe. *)";
  print_endline "";
  print_endline "let names =";
  print_endline "  [";
  S.iter (fun s -> Printf.printf "    %S;\n" s) set;
  print_endline "  ]"
