(* Read each argument path, infer a caller OCaml binding from its
   basename, and print a [runtime_bytes.ml] source that exposes the
   bytes as strings. *)

let read_all path =
  let ic = open_in_bin path in
  let n = in_channel_length ic in
  let s = Bytes.create n in
  really_input ic s 0 n;
  close_in ic;
  Bytes.unsafe_to_string s

let binding_name path =
  let base = Filename.basename path |> Filename.remove_extension in
  let buf = Buffer.create (String.length base) in
  String.iter
    (fun c ->
      match c with
      | 'A' .. 'Z' when Buffer.length buf > 0 ->
        Buffer.add_char buf '_';
        Buffer.add_char buf (Char.lowercase_ascii c)
      | 'A' .. 'Z' -> Buffer.add_char buf (Char.lowercase_ascii c)
      | _ -> Buffer.add_char buf c)
    base;
  Buffer.contents buf

let emit_string_literal out s =
  output_string out "\"";
  String.iter
    (fun c ->
      let n = Char.code c in
      Printf.fprintf out "\\x%02x" n)
    s;
  output_string out "\""

let () =
  let out = stdout in
  output_string out "(* Auto-generated by runtime-java/embed_class_bytes. *)\n\n";
  for i = 1 to Array.length Sys.argv - 1 do
    let path = Sys.argv.(i) in
    let name = binding_name path in
    let bytes = read_all path in
    Printf.fprintf out "let %s =\n  " name;
    emit_string_literal out bytes;
    output_string out "\n\n"
  done
